package me.rgunny.kachi.ai.domain.llm

/**
 * LLM 실패의 책임이 어디 있는가.
 *
 * 같은 실패라도 책임이 어디 있는지에 따라 다음 판단이 갈린다. 이 키워드의 문제면 다른 모델도 같은 결과를 줄 수 있고,
 * 모델이나 제공자의 문제면 그 단위만 빼면 된다. 호출이 나가기 전에 우리가 막은 실패는 어느 쪽 상태도 말해 주지 않는다.
 */
enum class LlmFailureAttribution {
    /** 이 키워드의 요청이나 응답. 거부된 요청 본문, 계약을 어긴 응답. */
    INPUT,

    /** 모델 하나. 제공이 끝났거나 이름이 틀린 모델. */
    MODEL,

    /** 계정과 endpoint. 인증·결제·한도, 서버 오류, 네트워크, rate limit. */
    PROVIDER,

    /** 우리 가드가 호출 전에 막았다. 제공자에 요청이 나가지 않았다. */
    NONE
}
